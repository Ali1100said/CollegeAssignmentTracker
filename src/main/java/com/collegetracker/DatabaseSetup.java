package com.collegetracker;

import java.sql.Connection;
import java.sql.SQLException;
import java.sql.Statement;
import java.sql.ResultSet;
import java.sql.DatabaseMetaData;

public class DatabaseSetup {

    private static boolean initialized = false;

    public static synchronized void initialize() throws SQLException {
        if (initialized) {
            return;
        }

        try (Connection conn = Database.getConnection();
             Statement stmt = conn.createStatement()) {

            stmt.executeUpdate(
                "CREATE TABLE IF NOT EXISTS students (" +
                "id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, " +
                "username VARCHAR(100) UNIQUE NOT NULL, " +
                "password_hash VARCHAR(255) NOT NULL, " +
                "email VARCHAR(255), " +
                "email_verified BOOLEAN DEFAULT FALSE, " +
                "full_name VARCHAR(150), " +
                "reset_token_hash VARCHAR(255), " +
                "reset_token_expires TIMESTAMP, " +
                "verification_token_hash VARCHAR(255))"
            );

            addColumnIfMissing(conn, "STUDENTS", "EMAIL",
                "VARCHAR(255)");
            addColumnIfMissing(conn, "STUDENTS", "EMAIL_VERIFIED",
                "BOOLEAN DEFAULT FALSE");
            addColumnIfMissing(conn, "STUDENTS", "FULL_NAME",
                "VARCHAR(150)");
            addColumnIfMissing(conn, "STUDENTS", "RESET_TOKEN_HASH",
                "VARCHAR(255)");
            addColumnIfMissing(conn, "STUDENTS", "RESET_TOKEN_EXPIRES",
                "TIMESTAMP");
            addColumnIfMissing(conn, "STUDENTS", "VERIFICATION_TOKEN_HASH",
                "VARCHAR(255)");

            stmt.executeUpdate(
                "CREATE TABLE IF NOT EXISTS courses (" +
                "id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, " +
                "student_id INTEGER NOT NULL, " +
                "course_name VARCHAR(150) NOT NULL, " +
                "FOREIGN KEY (student_id) REFERENCES students(id))"
            );

            stmt.executeUpdate(
                "CREATE TABLE IF NOT EXISTS assignments (" +
                "id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, " +
                "course_id INTEGER NOT NULL, " +
                "title VARCHAR(200) NOT NULL, " +
                "due_date DATE, " +
                "completed BOOLEAN DEFAULT FALSE, " +
                "FOREIGN KEY (course_id) REFERENCES courses(id))"
            );

            initialized = true;
        }
    }

    private static void addColumnIfMissing(
            Connection conn, String table,
            String column, String definition) throws SQLException {

        DatabaseMetaData metadata = conn.getMetaData();

        try (ResultSet rs = metadata.getColumns(
                null, "PUBLIC", table, column)) {

            if (rs.next()) {
                return;
            }
        }

        try (Statement stmt = conn.createStatement()) {
            stmt.executeUpdate(
                "ALTER TABLE " + table +
                " ADD COLUMN " + column + " " + definition
            );
        }
    }
}
